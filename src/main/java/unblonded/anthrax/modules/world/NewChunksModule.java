package unblonded.anthrax.modules.world;

import net.fabricmc.fabric.api.client.event.lifecycle.v1.ClientChunkEvents;
import net.fabricmc.loader.api.FabricLoader;
import net.minecraft.client.Minecraft;
import net.minecraft.client.multiplayer.ClientLevel;
import net.minecraft.core.BlockPos;
import net.minecraft.gizmos.GizmoStyle;
import net.minecraft.gizmos.Gizmos;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.LevelChunk;
import net.minecraft.world.level.chunk.LevelChunkSection;
import net.minecraft.world.phys.Vec3;
import unblonded.anthrax.modules.FeatureModule;
import unblonded.anthrax.modules.Setting;
import unblonded.anthrax.modules.visual.WorldOverlays;

import java.io.BufferedWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * New Chunks: tells freshly generated chunks (nobody has been here before) from old ones, and flags
 * chunks generated by an older game version.
 *
 *  - New: a chunk whose liquids start flowing right after it reaches us. Fresh terrain is generated
 *    with only still liquid; the server ticks it into flowing water and lava and sends those updates.
 *  - Old: a chunk that arrives with flowing liquid already in it, so it was generated and ticked before.
 *  - Old generation: an overworld chunk full of stone but without any copper ore, which every chunk
 *    generated since 1.17 has, so it was made by an older version (an old, long-explored area).
 *
 * Results are saved per server (or singleplayer world) and dimension in config/anthrax-chunks/.
 */
public final class NewChunksModule extends FeatureModule implements WorldOverlays.Overlay {
    public static final NewChunksModule INSTANCE = new NewChunksModule();

    public enum Kind {
        NEW("New", 0xFFFF4D6D), OLD("Old", 0xFF5CFF9D), OLD_GEN("Old generation", 0xFFFFC94A);
        public final String label;
        public final int color;
        Kind(String label, int color) { this.label = label; this.color = color; }
    }

    /** One classified chunk; {@code found} is when it was first classified (epoch ms). */
    public record Found(int cx, int cz, Kind kind, long found) {
        public int blockX() { return (cx << 4) + 8; }
        public int blockZ() { return (cz << 4) + 8; }
    }

    private static final Path DIR = FabricLoader.getInstance().getConfigDir().resolve("anthrax-chunks");
    /** Flowing-liquid updates this soon after a chunk arrives mean it was just generated. */
    private static final long NEW_WINDOW_MS = 6000;

    private final Setting.Bool showNew = setting(Setting.Bool.standalone("Show new chunks", true), "Chunks generated just now: nobody has been here before you.");
    private final Setting.Bool showOld = setting(Setting.Bool.standalone("Show old chunks", true), "Chunks that existed before you arrived: someone loaded them earlier.");
    private final Setting.Bool showOldGen = setting(Setting.Bool.standalone("Show old generation", true), "Chunks made by an older game version, usually areas explored long ago.");
    private final Setting.Mode height = setting(Setting.Mode.standalone("Draw height", "Feet", "Feet", "Sea level", "Bedrock"),
            "Where the chunk squares are drawn.");
    private final Setting.Num range = setting(Setting.Num.standalone("Render range (chunks)", 12, 2, 32, 1), "How far away chunk squares are drawn.");
    private final Setting.Num opacity = setting(Setting.Num.standalone("Fill opacity", 18, 0, 60, 2), "How strongly the squares are filled (outlines always show).");
    private final Setting.Bool save = setting(Setting.Bool.standalone("Remember per server", true),
            "Keep found chunks between sessions, separately for each server or world and dimension.");
    private final Setting.Action open = setting(new Setting.Action("Open chunk list", () ->
            Minecraft.getInstance().execute(() -> Minecraft.getInstance().gui.setScreen(new unblonded.anthrax.gui.ChunkListScreen()))),
            "Browse every found chunk, sorted by distance or time, with a mini map. Also: .chunks in chat.");

    private final Map<Long, Found> chunks = new HashMap<>();
    private final Map<Long, Long> arrived = new HashMap<>();
    private String loadedFor = "";
    private boolean dirty;
    private long nextSave;

    private NewChunksModule() {
        super("New Chunks", "Find freshly generated, old and old-version chunks; saved per server", "World", false);
        ClientChunkEvents.CHUNK_LOAD.register(this::onChunkLoad);
    }

    // ------------------------------------------------------------------ detection
    private void onChunkLoad(ClientLevel level, LevelChunk chunk) {
        if (!isEnabled()) return;
        ensureLoaded(level);
        ChunkPos pos = chunk.getPos();
        long key = pos.pack();
        arrived.put(key, System.currentTimeMillis());
        if (chunks.containsKey(key)) return;
        boolean flowing = false, copper = false;
        int stoneSections = 0;
        for (LevelChunkSection section : chunk.getSections()) {
            if (section == null || section.hasOnlyAir()) continue;
            if (!flowing && section.maybeHas(NewChunksModule::flowing)) flowing = true;
            if (!copper && section.maybeHas(s -> s.is(Blocks.COPPER_ORE) || s.is(Blocks.DEEPSLATE_COPPER_ORE))) copper = true;
            if (section.maybeHas(s -> s.is(Blocks.STONE))) stoneSections++;
        }
        if (level.dimension() == Level.OVERWORLD && !copper && stoneSections >= 4) put(pos, Kind.OLD_GEN);
        else if (flowing) put(pos, Kind.OLD);
    }

    /** Called from the packet mixin for every block change the server sends. */
    public void onBlockUpdate(BlockPos pos, BlockState state) {
        if (!isEnabled() || !flowing(state)) return;
        ChunkPos cp = ChunkPos.containing(pos);
        long key = cp.pack();
        Long at = arrived.get(key);
        // liquids starting to flow right after the chunk arrived: it was generated just now
        if (at != null && System.currentTimeMillis() - at < NEW_WINDOW_MS && !chunks.containsKey(key)) put(cp, Kind.NEW);
    }

    private static boolean flowing(BlockState s) {
        var fluid = s.getFluidState();
        return !fluid.isEmpty() && !fluid.isSource();
    }

    private void put(ChunkPos pos, Kind kind) {
        chunks.put(pos.pack(), new Found(pos.x(), pos.z(), kind, System.currentTimeMillis()));
        dirty = true;
    }

    // ------------------------------------------------------------------ persistence
    private static String serverId() {
        Minecraft mc = Minecraft.getInstance();
        if (mc.getCurrentServer() != null) return mc.getCurrentServer().ip;
        if (mc.getSingleplayerServer() != null) return "singleplayer/" + mc.getSingleplayerServer().getWorldData().getLevelName();
        return "unknown";
    }

    private Path file(ClientLevel level) {
        String server = serverId().replaceAll("[^A-Za-z0-9._-]", "_");
        String dim = level.dimension().identifier().toString().replaceAll("[^A-Za-z0-9._-]", "_");
        return DIR.resolve(server).resolve(dim + ".csv");
    }

    /** Switches to the saved chunks of the current server and dimension when either changes. */
    private void ensureLoaded(ClientLevel level) {
        String id = serverId() + "|" + level.dimension().identifier();
        if (id.equals(loadedFor)) return;
        flush();
        loadedFor = id;
        chunks.clear();
        arrived.clear();
        if (!save.get()) return;
        Path f = file(level);
        if (!Files.isRegularFile(f)) return;
        try {
            for (String line : Files.readAllLines(f, StandardCharsets.UTF_8)) {
                String[] p = line.split(",");
                if (p.length < 4) continue;
                try {
                    int cx = Integer.parseInt(p[0]), cz = Integer.parseInt(p[1]);
                    chunks.put(ChunkPos.pack(cx, cz), new Found(cx, cz, Kind.valueOf(p[2]), Long.parseLong(p[3])));
                } catch (IllegalArgumentException ignored) {}
            }
        } catch (Exception e) {
            System.err.println("Anthrax: could not read chunk log: " + e.getMessage());
        }
    }

    /** Writes the current chunks off the client thread. */
    private void flush() {
        Minecraft mc = Minecraft.getInstance();
        if (!dirty || !save.get() || mc.level == null || loadedFor.isEmpty()) { dirty = false; return; }
        dirty = false;
        Path f = file(mc.level);
        List<Found> copy = new ArrayList<>(chunks.values());
        Thread.ofVirtual().start(() -> {
            synchronized (NewChunksModule.class) {
                try {
                    Files.createDirectories(f.getParent());
                    Path tmp = f.resolveSibling(f.getFileName() + ".tmp");
                    try (BufferedWriter w = Files.newBufferedWriter(tmp, StandardCharsets.UTF_8)) {
                        for (Found c : copy) { w.write(c.cx + "," + c.cz + "," + c.kind.name() + "," + c.found); w.newLine(); }
                    }
                    Files.move(tmp, f, java.nio.file.StandardCopyOption.REPLACE_EXISTING);
                } catch (Exception e) {
                    System.err.println("Anthrax: could not save chunk log: " + e.getMessage());
                }
            }
        });
    }

    @Override public void tick(Minecraft mc) {
        if (mc.level == null) return;
        ensureLoaded(mc.level);
        long now = System.currentTimeMillis();
        if (now >= nextSave) { nextSave = now + 20_000; flush(); }
        if (arrived.size() > 20_000) arrived.entrySet().removeIf(e -> now - e.getValue() > NEW_WINDOW_MS);
    }

    @Override protected void onToggle(boolean enabled) {
        if (!enabled) flush();
        else loadedFor = "";   // reload for wherever we are now
    }

    // ------------------------------------------------------------------ API for the list screen
    public List<Found> found() { return new ArrayList<>(chunks.values()); }

    public boolean visible(Kind k) {
        return switch (k) { case NEW -> showNew.get(); case OLD -> showOld.get(); case OLD_GEN -> showOldGen.get(); };
    }

    public void remove(Found f) { chunks.remove(ChunkPos.pack(f.cx, f.cz)); dirty = true; }

    public void clearHere() { chunks.clear(); dirty = true; flush(); }

    public String placeName() {
        Minecraft mc = Minecraft.getInstance();
        return serverId() + (mc.level == null ? "" : "  ·  " + mc.level.dimension().identifier().getPath());
    }

    // ------------------------------------------------------------------ world overlay
    @Override public boolean active() { return isEnabled() && !chunks.isEmpty(); }

    @Override public void draw(Minecraft mc, float partial, Vec3 eye, Vec3 look) {
        if (mc.player == null || mc.level == null) return;
        double y = switch (height.get()) {
            case "Sea level" -> mc.level.getSeaLevel();
            case "Bedrock" -> mc.level.getMinY() + 1;
            default -> Math.floor(mc.player.getY(partial)) + .02;
        };
        int pcx = mc.player.getBlockX() >> 4, pcz = mc.player.getBlockZ() >> 4, r = (int) range.get();
        int fillA = (int) (opacity.get() * 2.55);
        for (Found c : chunks.values()) {
            if (!visible(c.kind) || Math.abs(c.cx - pcx) > r || Math.abs(c.cz - pcz) > r) continue;
            double x0 = c.cx * 16 + .3, z0 = c.cz * 16 + .3, x1 = x0 + 15.4, z1 = z0 + 15.4;
            Vec3 a = new Vec3(x0, y, z0), b = new Vec3(x1, y, z0), cc = new Vec3(x1, y, z1), d = new Vec3(x0, y, z1);
            if (fillA > 0) {
                GizmoStyle fill = GizmoStyle.fill(WorldOverlays.argb(fillA, c.kind.color));
                Gizmos.rect(a, b, cc, d, fill);
                Gizmos.rect(d, cc, b, a, fill);
            }
            int line = WorldOverlays.argb(0xB0, c.kind.color);
            Gizmos.line(a, b, line, 1.6f);
            Gizmos.line(b, cc, line, 1.6f);
            Gizmos.line(cc, d, line, 1.6f);
            Gizmos.line(d, a, line, 1.6f);
        }
    }

    @Override public String hudInfo() {
        int n = 0, o = 0;
        for (Found c : chunks.values()) if (c.kind == Kind.NEW) n++; else o++;
        return n + " new  " + o + " old";
    }
}
